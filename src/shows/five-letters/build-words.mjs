// Builds words.ts from the `wordlist-english` npm package (a repackaging of SCOWL, http://wordlist.aspell.net/).
// Run by hand when the list should change: node src/shows/five-letters/build-words.mjs <path to the unpacked package>
// Answers come from SCOWL sizes 10 and 20 (the commonest words); guesses are also accepted from sizes 40 to 70.
// Nothing here runs in the extension, and nothing is fetched at run time: words.ts ships in the bundle.
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { URL } from 'node:url';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the path to the unpacked wordlist-english package.');
const five = (size) =>
  JSON.parse(readFileSync(`${dir}/english-words-${size}.json`, 'utf8')).filter((w) => /^[a-z]{5}$/.test(w));

// Words nobody wants on a sofa during an ad break, kept out of the answers (still not accepted as guesses).
const RUDE = new Set(
  'whore slut bitch bastard dyke fucks fucked cunts shits piss pisses pissed nazis rapes raped rapist sluts whores negro coons spick kikes chink wanks wanker tarts bimbo crap craps boobs titty tits penis semen vagina anus anal sexed sexes nudes porno dildo'.split(' '),
);
const plural = (w) => w.endsWith('s') && !w.endsWith('ss') && !w.endsWith('us') && !w.endsWith('is');

const answers = [...new Set([10, 20].flatMap(five))].filter((w) => !RUDE.has(w) && !plural(w)).sort();
const valid = [...new Set([...answers, ...[10, 20, 35, 40, 50, 55, 60, 70].flatMap(five)])].filter((w) => !RUDE.has(w)).sort();

const out = `// Generated by build-words.mjs from SCOWL (see SCOWL-COPYRIGHT.txt). Do not edit by hand.
// ANSWERS: ${answers.length} common words a break's word can be. VALID: ${valid.length} words a guess can be.
export const ANSWERS: readonly string[] = '${answers.join(' ')}'.split(' ');
export const VALID: ReadonlySet<string> = new Set('${valid.join(' ')}'.split(' '));
`;
writeFileSync(new URL('./words.ts', import.meta.url), out);
process.stdout.write(`${answers.length} answers, ${valid.length} valid guesses\n`);
